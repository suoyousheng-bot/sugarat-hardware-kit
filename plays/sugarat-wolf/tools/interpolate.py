"""Double the frame rate of the Wolf Companion art with optical-flow in-between frames.

The original frames move 9-14 px per frame (90th percentile) in head turns, the sofa jump and the zoom
shots, which reads as judder at any playback rate. This tool inserts one motion-compensated frame between
every adjacent pair inside each continuous segment (clips, and each row of the gaze grid) and writes
frames_x2/f000.jpg..., plus firmware/main/wolf_frames.h mapping original indexes to new ones. Original
frames are copied byte for byte; in-between frames are encoded as baseline 4:2:0 JPEG.

Requires opencv-python-headless and numpy.
Usage: python3 interpolate.py <frames_dir> <out_dir> <out_header>
"""
import shutil
import sys
from pathlib import Path

import cv2
import numpy as np

# Continuous runs of the original art; there is a cut between runs.
SEGMENTS = [(0, 71), (72, 255), (256, 264), (265, 277), (278, 286)]
JPEG_QUALITY = 82


def flow(a, b):
    ga, gb = cv2.cvtColor(a, cv2.COLOR_BGR2GRAY), cv2.cvtColor(b, cv2.COLOR_BGR2GRAY)
    return cv2.calcOpticalFlowFarneback(ga, gb, None, 0.5, 5, 25, 7, 7, 1.5, 0)


def warp(img, fl, t):
    h, w = fl.shape[:2]
    gx, gy = np.meshgrid(np.arange(w, dtype=np.float32), np.arange(h, dtype=np.float32))
    return cv2.remap(img, gx - fl[..., 0] * t, gy - fl[..., 1] * t, cv2.INTER_LINEAR, borderValue=0)


def midpoint(a, b):
    """Warps both neighbours halfway along their flows toward each other and averages them."""
    return cv2.addWeighted(warp(a, flow(a, b), 0.5), 0.5, warp(b, flow(b, a), 0.5), 0.5, 0)


def main():
    src, out, header = Path(sys.argv[1]), Path(sys.argv[2]), Path(sys.argv[3])
    out.mkdir(parents=True, exist_ok=True)
    for old in out.glob("f*.jpg"):
        old.unlink()
    mapping = {}
    index = 0

    def emit_copy(i):
        nonlocal index
        mapping[i] = index
        shutil.copyfile(src / f"f{i:03d}.jpg", out / f"f{index:03d}.jpg")
        index += 1

    for first, last in SEGMENTS:
        for i in range(first, last + 1):
            emit_copy(i)
            if i < last:
                a, b = cv2.imread(str(src / f"f{i:03d}.jpg")), cv2.imread(str(src / f"f{i + 1:03d}.jpg"))
                cv2.imwrite(str(out / f"f{index:03d}.jpg"), midpoint(a, b), [cv2.IMWRITE_JPEG_QUALITY, JPEG_QUALITY])
                index += 1
    lines = ["/** Generated by tools/interpolate.py; do not edit. */", "#pragma once", "",
             "/** New frame index of each original Wolf Companion frame; an in-between frame follows each one",
             " *  inside a continuous segment. */",
             f"static const short wolf_src_frame[{len(mapping)}] = {{"]
    values = [str(mapping[i]) for i in range(len(mapping))]
    for k in range(0, len(values), 16):
        lines.append("    " + ", ".join(values[k:k + 16]) + ",")
    lines += ["};", "", f"#define WOLF_FRAME_COUNT {index}", ""]
    header.write_text("\n".join(lines))
    print(f"{len(mapping)} original frames -> {index} frames in {out}")


if __name__ == "__main__":
    main()
